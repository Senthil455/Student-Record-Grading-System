CREATE TABLE IF NOT EXISTS persons (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name    VARCHAR(60)  NOT NULL,
    last_name     VARCHAR(60)  NOT NULL,
    email         VARCHAR(120) NOT NULL UNIQUE,
    phone         VARCHAR(20),
    date_of_birth DATE,
    created_at    TIMESTAMP(6) NOT NULL
);

CREATE TABLE IF NOT EXISTS students (
    person_id      BIGINT      NOT NULL PRIMARY KEY,
    roll_number    VARCHAR(20) NOT NULL UNIQUE,
    department     VARCHAR(80) NOT NULL,
    admission_year INT         NOT NULL,
    active         BOOLEAN     NOT NULL,
    CONSTRAINT fk_student_person FOREIGN KEY (person_id) REFERENCES persons (id)
);

CREATE TABLE IF NOT EXISTS instructors (
    person_id      BIGINT       NOT NULL PRIMARY KEY,
    employee_code  VARCHAR(20)  NOT NULL UNIQUE,
    designation    VARCHAR(80),
    specialization VARCHAR(120),
    CONSTRAINT fk_instructor_person FOREIGN KEY (person_id) REFERENCES persons (id)
);

CREATE TABLE IF NOT EXISTS courses (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_code   VARCHAR(15)  NOT NULL UNIQUE,
    title         VARCHAR(120) NOT NULL,
    credits       INT          NOT NULL,
    semester      INT          NOT NULL,
    department    VARCHAR(80),
    description   VARCHAR(500),
    instructor_id BIGINT,
    CONSTRAINT fk_course_instructor FOREIGN KEY (instructor_id) REFERENCES instructors (person_id)
);

CREATE TABLE IF NOT EXISTS enrollments (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id  BIGINT      NOT NULL,
    course_id   BIGINT      NOT NULL,
    marks       DOUBLE,
    grade       VARCHAR(3),
    grade_point DOUBLE,
    semester    INT         NOT NULL,
    enrolled_on DATE        NOT NULL,
    graded_by   VARCHAR(30),
    CONSTRAINT uk_enrollment_student_course UNIQUE (student_id, course_id),
    CONSTRAINT fk_enrollment_student FOREIGN KEY (student_id) REFERENCES students (person_id),
    CONSTRAINT fk_enrollment_course FOREIGN KEY (course_id) REFERENCES courses (id)
);
